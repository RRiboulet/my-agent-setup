#!/usr/bin/env node
/**
 * skills-index — render the README's skill inventory from the skills themselves.
 *
 * The README used to describe 24 of 25 skills by hand and label only the five
 * user-invoked ones, so "unlabelled means model-invoked" was a convention a
 * reader had to infer, one skill was missing entirely, and every description
 * rewrite had to be copied into a table by hand. This renders the table from
 * each `SKILL.md`'s frontmatter instead: the frontmatter is the single source of
 * truth for a skill's name, its invocation class (`disable-model-invocation`)
 * and its trigger text, and `--check` fails when the README disagrees.
 *
 * Usage:
 *   node tools/skills-index.mjs            # print the block
 *   node tools/skills-index.mjs --write    # replace the block in README.md
 *   node tools/skills-index.mjs --check    # exit 1 when README.md is stale
 *
 * The block lives between the two markers below. Everything outside them is
 * hand-written prose: the rules about who may invoke what are not generated,
 * because they are judgement, not a list.
 *
 * Node stdlib only; no dependencies, like every other tool here.
 */

import fs from "node:fs";
import path from "node:path";

const REPO_ROOT = path.resolve(new URL("..", import.meta.url).pathname);
const SKILLS_DIR = path.join(REPO_ROOT, "skills");
const README = path.join(REPO_ROOT, "README.md");

export const BEGIN = "<!-- skills-index:begin — generated by tools/skills-index.mjs --write; do not edit by hand -->";
export const END = "<!-- skills-index:end -->";

/** `name`, `description` and `disable-model-invocation` from one skill's frontmatter. */
export function readSkill(dir) {
  const text = fs.readFileSync(path.join(SKILLS_DIR, dir, "SKILL.md"), "utf8");
  const lines = text.split("\n");
  if (lines[0].trim() !== "---") throw new Error(`${dir}/SKILL.md has no frontmatter`);
  const end = lines.findIndex((line, index) => index > 0 && line.trim() === "---");
  if (end === -1) throw new Error(`${dir}/SKILL.md has unterminated frontmatter`);
  const meta = {};
  for (const line of lines.slice(1, end)) {
    const match = /^([A-Za-z0-9_-]+):\s*(.*)$/.exec(line);
    if (match) meta[match[1]] = match[2].replace(/^"|"$/g, "");
  }
  if (!meta.description) throw new Error(`${dir}/SKILL.md has no description`);
  return {
    dir,
    name: meta.name ?? dir,
    description: meta.description,
    userInvoked: meta["disable-model-invocation"] === "true",
  };
}

/** Every skill, sorted by name, with the invocation class the frontmatter declares. */
export function readSkills() {
  return fs
    .readdirSync(SKILLS_DIR, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => readSkill(entry.name))
    .sort((a, b) => a.name.localeCompare(b.name));
}

/** A markdown table cell: pipes would end the cell, newlines would end the row. */
function cell(text) {
  return text.replace(/\|/g, "\\|").replace(/\s*\n\s*/g, " ").trim();
}

function table(skills) {
  const rows = skills.map((skill) => {
    const label = skill.userInvoked ? `/${skill.name}` : skill.name;
    return `| [\`${label}\`](skills/${skill.dir}/SKILL.md) | ${cell(skill.description)} |`;
  });
  return ["| Skill | What it does, and when to reach for it |", "|---|---|", ...rows].join("\n");
}

/**
 * The generated block. The count line is rendered too, so a skill added or
 * removed shows up as a diff here rather than in a stale sentence elsewhere.
 */
export function renderBlock(skills = readSkills()) {
  const userInvoked = skills.filter((skill) => skill.userInvoked);
  const modelInvoked = skills.filter((skill) => !skill.userInvoked);
  return [
    BEGIN,
    "",
    `### User-invoked — ${userInvoked.length}: only you can start these, by typing \`/skill:<name>\``,
    "",
    table(userInvoked),
    "",
    `### Model-invoked — ${modelInvoked.length}: you can type \`/skill:<name>\`, and the agent loads one itself when its description matches`,
    "",
    table(modelInvoked),
    "",
    END,
  ].join("\n");
}

/** The README with its block replaced (or the block appended when the markers are missing). */
export function renderReadme(readme = fs.readFileSync(README, "utf8"), block = renderBlock()) {
  const start = readme.indexOf(BEGIN);
  const end = readme.indexOf(END);
  if (start === -1 && end === -1) return `${readme.replace(/\s*$/, "")}\n\n${block}\n`;
  if (start === -1 || end === -1 || end < start) {
    throw new Error("README.md has one skills-index marker but not the other; fix the markers by hand");
  }
  return `${readme.slice(0, start)}${block}${readme.slice(end + END.length)}`;
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === path.resolve(new URL(import.meta.url).pathname);

if (isMain) {
  const args = new Set(process.argv.slice(2));
  const current = fs.readFileSync(README, "utf8");
  const block = renderBlock();
  if (args.has("--write")) {
    fs.writeFileSync(README, renderReadme(current, block));
    console.log(`skills-index: README.md updated (${readSkills().length} skills)`);
  } else if (args.has("--check")) {
    if (!current.includes(block)) {
      console.error("skills-index: README.md is stale — run: node tools/skills-index.mjs --write");
      const start = current.indexOf(BEGIN);
      const end = current.indexOf(END);
      if (start !== -1 && end !== -1) {
        console.error("\nexpected block:\n" + block + "\n\nfound:\n" + current.slice(start, end + END.length));
      }
      process.exit(1);
    }
    console.log(`skills-index: README.md matches the ${readSkills().length} skills on disk`);
  } else {
    console.log(block);
  }
}
